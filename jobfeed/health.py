"""Стан кожного джерела: чи забралось, скільки, і якщо ні — чому.

Навіщо окремий модуль, а не поле в звіті прогону
------------------------------------------------
Звіт живе один прогін. Питання власника — «чи скрапиться воно успішно» —
про ІСТОРІЮ: джерело, яке впало щойно, і джерело, яке мовчить третій день,
у поточному прогоні виглядають однаково (нуль вакансій, один рядок помилки).
Розрізняє їх лише `last_ok`, а його треба десь тримати між прогонами.

🔴 ГОЛОВНЕ, ЗАРАДИ ЧОГО ЦЕ НАПИСАНО
-----------------------------------
Перелік джерел у меню досі будувався **зі зібраних вакансій**. Тобто рядок
джерела існував рівно доти, доки джерело щось віддавало. Djinni падає —
рядок `Djinni 169` зникає, і в меню лишаються DOU й HappyMonday, кожен зі
своїм здоровим числом. Сторінка виглядає бездоганно; зникнення двох третин
стрічки видно лише тому, кому є з чим порівняти.

Це той самий клас, що дайджест, який не оновився: **про поломку свідчила
ВІДСУТНІСТЬ рядка**. Тому перелік тепер будується з КОНФІГА — усі
налаштовані джерела, включно з тими, що не віддали нічого й не забирались
жодного разу. Рядок є завжди; змінюється лише його стан.

Стани й що вони означають
-------------------------
`ok`      забралось, віддало більше нуля
`quiet`   ІНКРЕМЕНТАЛЬНЕ джерело віддало нуль — це нормальний робочий стан,
          а не збій: воно й повертає лише те, що зʼявилось після мітки
          минулого забору. Нуль тут означає «нічого нового», і плутати його
          з порожнім фідом не можна — це різні твердження
`empty`   джерело, яке щоразу віддає ПОВНУ вибірку, віддало нуль. Не помилка
          (фід міг спорожніти), але й не «все гаразд» — окремий стан
`failed`  впало — тримаємо причину текстом, бо «червоний колір» не
          відповідає на питання, що робити
`off`     вимкнене в конфізі — причина з `note`, як у Andersen
`waiting` джерело має власну періодичність (фіди компаній — раз на добу) і
          цього прогону свідомо не забиралось. НЕ збій і НЕ порожнеча:
          вакансії лишаються на сторінці, сигнал зникнення для нього
          вимикається явно й з названою причиною
`unknown` стану ще немає в памʼяті

⚠️ `unknown` — це твердження про НАШУ памʼять, а не про джерело.
Перша версія писала тут «жодного разу не забиралось», і на першому ж прогоні
HappyMonday отримав цей рядок, маючи 19 своїх карток на екрані. Поміряно було
«немає запису в історії», сказано — «джерело не працює»: рівно та підміна
сусідньої величини, яку ми ловимо всю сесію, тільки цього разу вона друкувалась
би власнику як діагноз.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone

META_KEY = "source_health"


@dataclass
class SourceHealth:
    name: str
    state: str = "unknown"
    # Чи віддає джерело повну вибірку щоразу. Від цього залежить, ЩО означає
    # нуль: для інкрементального — «нічого нового», для повного — «фід порожній».
    full_scan: bool = True
    # Скільки джерело віддало САМЕ ЦИМ забором.
    #
    # ⚠️ Це не те саме, що число біля назви джерела в меню. Там — картки у
    # вікні сторінки (14 днів), тут — що прийшло з фіда зараз. Числа різні
    # законно, і плутати їх не можна: рівно так народжуються наші улюблені
    # помилки, коли поміряно одну величину, а сказано про сусідню.
    fetched: int = 0
    error: str = ""
    # Чи побачили ми ВЕСЬ фід, чи уперлись у стелю сторінок.
    #
    # Обрізаний забір — це успіх, який виглядає як повний успіх: помилки
    # немає, число більше нуля, рядок зелений. Різниця лише в тому, що
    # частини вакансій ми не бачили й ніколи про це не скажемо. Досі цей
    # факт жив тільки в попередженні в консолі, куди власник не дивиться.
    complete: bool = True
    note: str = ""
    last_ok: str = ""
    last_try: str = ""
    # Скільки віддало ОСТАННЄ вдале забирання. Потрібне, щоб на впалому
    # прогоні показати не лише «коли», а й «скільки тоді було».
    last_ok_count: int = 0
    # Скільки годин до наступного забору — для джерел із власною
    # періодичністю. Стан `waiting` це НЕ збій і не порожнеча.
    wait_hours: float = 0.0
    # Стан кожного фіда всередині джерела: {мітка: {state, count, error}}.
    feeds: dict = field(default_factory=dict)

    @property
    def healthy(self) -> bool:
        return self.state == "ok"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def load(store) -> dict[str, SourceHealth]:
    """Історія станів із памʼяті. Порожньо/зіпсовано — починаємо з нуля."""
    raw = store.get_meta(META_KEY, "")
    if not raw:
        return {}
    try:
        data = json.loads(raw)
    except (ValueError, TypeError):
        # Зіпсований запис не має валити прогін: це діагностика, а не дані.
        return {}
    result = {}
    for name, item in (data or {}).items():
        if not isinstance(item, dict):
            continue
        # Ключі відсіюємо за полями САМОГО класу: запис у базі пережив уже
        # одну зміну схеми (додався `full_scan`), і переживе наступні —
        # старий запис без нового поля мусить читатись, а не валити прогін.
        allowed = {k: v for k, v in item.items() if k in SourceHealth.__annotations__}
        allowed["name"] = name
        result[name] = SourceHealth(**allowed)
    return result


def save(store, healths: dict[str, SourceHealth]) -> None:
    store.set_meta(META_KEY, json.dumps(
        {name: asdict(h) for name, h in healths.items()}, ensure_ascii=False
    ))


def merge(previous: dict[str, SourceHealth], current: SourceHealth) -> SourceHealth:
    """Нове забирання поверх памʼяті.

    `last_ok` переносимо з попереднього стану, якщо цього разу не вдалось, —
    інакше «востаннє успішно» показувало б час НЕВДАЛОЇ спроби, тобто
    сигнал про застаріле джерело сам би виглядав свіжим. Та сама пастка,
    що з віком сторінки: мітка часу мусить відповідати на питання «коли
    востаннє СПРАЦЮВАЛО», а не «коли ми востаннє пробували».
    """
    old = previous.get(current.name)
    current.last_try = _now()
    if current.state == "waiting" and old:
        # Пропущений прогін не є спробою: інакше мітка `last_try` зсувалась би
        # щогодини й доба ніколи б не наставала.
        current.last_try = old.last_try
        current.last_ok = old.last_ok
        current.last_ok_count = old.last_ok_count
        current.feeds = old.feeds or current.feeds
        return current
    if current.state == "ok":
        current.last_ok = current.last_try
        current.last_ok_count = current.fetched
    elif old:
        current.last_ok = old.last_ok
        current.last_ok_count = old.last_ok_count
        # Джерело, що вже колись віддавало, а тепер порожнє, — це не
        # «ще жодного разу». Стан лишається тим, що поміряно зараз,
        # але історія не стирається.
    # Нуль у інкрементального джерела — робочий стан, а не збій: воно й
    # віддає тільки те, що зʼявилось після мітки. Якби ми лишили тут "empty",
    # HappyMonday світився б попередженням у КОЖНОМУ прогоні, де нічого не
    # опублікували, — і попередження перестало б щось означати.
    if current.state == "empty" and not current.full_scan:
        current.state = "quiet"
    return current


def collect_states(config_sources: dict, live_names: set[str]) -> dict[str, str]:
    """Причини вимкнення з конфіга — для джерел, яких у прогоні не було.

    Джерело з `enabled = false` не потрапляє в `build()`, отже про нього не
    буде ані вакансій, ані помилки. Без цього кроку воно зникло б із меню
    цілком — тобто саме те, від чого цей модуль і існує.
    """
    off = {}
    for name, section in (config_sources or {}).items():
        if name in live_names:
            continue
        if not section.get("enabled", True):
            off[name] = str(section.get("note", "") or "вимкнене в конфізі")
    return off
