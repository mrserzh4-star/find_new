    # Критичний sink, що впав, НЕ має виглядати як рядок серед інших:
    # прогін із мертвим дайджестом друкує повне здорове зведення — зібрано,
    # відфільтровано, заповненість, бронь — і відрізняється від успішного
    # лише ВІДСУТНІСТЮ рядка «дайджест:». А відсутність рядка око не ловить:
    # ми привчені перевіряти те, що написано.
    #
    # Наслідок без цього прапорця: сервіс щогодини успішно збирає вакансії,
    # пише в базу, друкує здорові цифри — а сторінка не оновлюється тижнями,
    # і власник дивиться на застиглу стрічку, гадаючи, що вакансій просто
    # немає. Це той самий клас, що й решта наших тихих поломок, тільки на
    # головному шляху.
