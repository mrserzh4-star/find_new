"""Sink — куди віддаємо результат.

Свідомо ширший за «відправника повідомлень»: sink отримує ВЕСЬ зріз
(і свіже, і те, що вже показували), бо сторінка-дайджест — це стан,
а не разове повідомлення. Месенджерний sink просто проігнорує старе
і візьме `is_new == True`.

Додати доставку в месенджер = ще один модуль тут + рядок у конфізі.
Ядро (`pipeline.py`) не міняється.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from ..models import Entry


@runtime_checkable
class Sink(Protocol):
    name: str

    # Чи є цей вихід тим, заради чого сервіс працює.
