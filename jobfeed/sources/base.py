"""Спільний інтерфейс джерела.

Новий сайт = новий модуль у `jobfeed/sources/`, який реалізує `Source`
і реєструється у `jobfeed/sources/__init__.py`. Ядро (фільтр, дедуп,
відправка) про конкретні сайти нічого не знає.
"""

from __future__ import annotations

from typing import Iterable, Protocol, runtime_checkable

from ..models import Vacancy


class AdapterContractError(RuntimeError):
    """Адаптер порушив контракт джерела.

    Це помилка РОЗРОБНИКА адаптера, а не стан даних, тому вона падає, а не
    стає попередженням: попередження живе поруч із мережевими збоями, які
    минають самі, і серед них таку річ не помітять.
    """


@runtime_checkable
class Source(Protocol):
    name: str

    # "board" — джоб-борд, де публікуються різні компанії.
    # "company" — власний сайт однієї компанії.
    # Розрізнення потрібне у видачі: власник дивиться на них по-різному.
    kind: str = "board"

    # Назви полів `Vacancy`, які це джерело здатне заповнити. Потрібні
    # зведенню заповненості: без оголошення знаменник довелось би виводити
    # з побачених значень, а такий знаменник зникає разом із полем — тобто
    # показник сліпне рівно тоді, коли він потрібен.
    provides: frozenset[str] = frozenset()

    # Чи вдалося забрати вибірку ЦІЛКОМ у цьому прогоні. Ставиться в False
    # лише тим, що впливає на ПОВНОТУ забору: обрізана пагінація, пропущений
    # фід, порожня відповідь. Попередження, які повноти не стосуються (напр.
    # вичерпаний бюджет збагачення деталей), сюди НЕ входять — інакше сигнал
    # «зникла з фіда» вимикався б там, де фід насправді прочитано повністю.
    fetch_complete: bool = True

    # Чи віддає джерело ПОВНУ вибірку за своє вікно при кожному заборі.
    #
    # Це не дрібниця: на цьому тримається сигнал «вакансія зникла з фіда,
    # отже ймовірно закрита». Для джерела, яке тягне інкрементально (віддає
    # лише те, що з'явилось після минулого разу), відсутність запису означає
    # просто «не нова» — і той сигнал перетворив би всю його видачу на
    # «ймовірно закриті» вже за два прогони.
    scans_full_feed: bool = True

    def fetch(self) -> Iterable[Vacancy]:
        """Повертає вакансії джерела, вже зведені до `Vacancy`.

        Мережеві помилки піднімає назовні — пайплайн ловить їх і продовжує
        з рештою джерел (одне впале джерело не валить прогін).
        """
        ...


@runtime_checkable
class Enrichable(Protocol):
    """Джерело, якому для повної картки потрібен ще один запит на вакансію.

    Необовʼязковий інтерфейс. Реалізують його ті джерела, чий список
    (RSS) не містить усіх полів, а сторінка вакансії містить — наприклад
    Djinni, де company і location є лише в JSON-LD на сторінці.

    Ядро викликає `enrich()` ТІЛЬКИ для вакансій, яких ще немає в базі.
    Це і робить схему «1 запит на фід + N на нові» дешевою: за звичайний
    цикл нових одиниці, а не сотні. Джерело не мусить саме знати, що нове —
    цю відповідь має тільки база.
    """

    name: str

    def enrich(self, vacancies: list[Vacancy]) -> list[Vacancy]:
        ...


@runtime_checkable
class Incremental(Protocol):
    """Джерело, яке вміє тягнути тільки те, що зʼявилось після минулого разу.

    Необовʼязковий інтерфейс. Ядро перед `fetch()` кладе в `cursor` мітку
    минулого успішного забору, а після — забирає `next_cursor` і зберігає її.
    Саме джерело нічого не знає про базу: мітка це просто рядок.

    Навіщо: у HappyMonday без цього довелось би щогодини тягнути все вікно
    сторінка за сторінкою, тоді як з міткою цикл — один запит на одиниці
    записів. Мітку джерело зсуває ЛИШЕ після повного успішного проходу,
    інакше впалий прогін лишив би дірку назавжди.
    """

    name: str
    cursor: str
    next_cursor: str
