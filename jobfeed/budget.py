"""Бюджет вакансії з тіла опису — коли джерело не дало поля `salary`.

Чому не «знайти в описі гроші»
------------------------------
Заміряно на 243 живих вакансіях:

    поле `salary` заповнене                 27
    без поля, але гроші в описі             14
    з них справжня зарплата                  6

**Тобто наївний пошук грошей помиляється у 8 випадках із 14 — більше ніж
у половині.** Ось що він приніс би на картку:

    clients have raised $500M+                 інвестиції клієнтів
    Великі (>$1,000,000 monthly) бюджети       рекламний бюджет
    $1.19 trillion e-commerce industry         розмір ринку
    scaled from $2M → $50M in ARR              виторг продукту
    Referral bonus — $200                      бонус за рекомендацію
    courses/certifications (200 EUR per year)  пільга

Ціна помилки тут вища, ніж із рівнем англійської: `$500M` у чипі зарплати
власник прочитає не як «ми помилились», а як знущання.

Правило те саме, що з мовою
---------------------------
1. **Сума сама по собі не є доказом.** Поруч має стояти слово, яке каже, що
   це винагорода: `compensation`, `salary`, `заробітна плата`, `оклад`,
   `ставка`, `винагорода`, `вилка`.
2. **Стоп-контекст сильніший за контекст.** `raised`, `bonus`, `бюджет`,
   `industry`, `ARR`, `valuation` означають, що гроші не про зарплату, —
   навіть якщо поруч випадково трапилось слово `rate`.

Вікно ±60 символів — заміряно, як і для мови:

    ±40 → 4 знайдено, 0 хибних   (губить `Financial Stability: $1,500/month`)
    ±60 → 6 знайдено, 0 хибних   ← беремо
    ±80 → 6 знайдено, 1 хибний   (`courses (200 EUR per year)`)

Тобто 80 уже чіпляє пільгу за курси, а 40 не дістає законних. 60 — єдине
вікно, де всі шість справжніх і жодного хибного.

🔴 Діапазон не можна обрізати
-----------------------------
Перша версія віддавала `1,500–2,000 USD` як `2,000 USD` — тобто **верхню
межу**, бо збіг починався з другого числа. Це гірше за обрізання діапазону
рівня англійської: там ми занижували вимогу, а тут завищували б пропозицію.

Тому діапазон захоплюється цілим, разом із періодичністю (`/month`,
`per month`, `на місяць`) — без неї `$1,500` і `$1,500/month` виглядають
однаково, а це різні твердження.
"""

from __future__ import annotations

import re

# Вікно — див. замір у докстрінгу модуля.
WINDOW = 60

_CURRENCY = r"[$€₴£]"
_WORD_CURRENCY = r"(?:USD|EUR|UAH|GBP|грн|дол\w*|євро)"
_NUMBER = r"\d[\d  .,]*\d|\d"

# Одна сума: валюта символом попереду і/або словом позаду.
_ELEMENT = rf"(?:{_CURRENCY}\s?)?(?:{_NUMBER})(?:\s?{_WORD_CURRENCY})?"
_RANGE_SEP = r"\s?(?:[–—−-]|to|до)\s?"
# Періодичність — частина твердження, не прикраса: `$1,500` і `$1,500/month`
# різні речі.
_PERIOD = (r"(?:\s?(?:/|per\s|на\s|в\s)\s?"
           r"(?:month|mo|year|hour|місяць|міс|рік|годину))")

# Діапазон захоплюється ЦІЛИМ. Перша версія віддавала `1,500–2,000 USD` як
# `2,000 USD` — верхню межу, бо збіг починався з другого числа. Для зарплати
# це гірше, ніж обрізати діапазон рівня мови: там ми занижували вимогу, тут
# завищували б пропозицію.
MONEY = re.compile(
    rf"(?P<sum>{_ELEMENT}(?:{_RANGE_SEP}{_ELEMENT})?)(?P<period>{_PERIOD})?",
    re.IGNORECASE,
)

# Слово, що робить суму винагородою. Без нього чипа немає.
CONTEXT = re.compile(
    r"compensation|salary|payroll|зарплат\w*|заробітн\w*\s+плат\w*|оклад|"
    r"ставка|винагород\w*|вилка|pay\s+range|rate\b",
    re.IGNORECASE,
)

# 🔴 Сильніше за контекст: якщо поруч є щось із цього, гроші не про зарплату.
# Перевірено на живих описах — саме ці слова стоять біля хибних збігів.
STOP = re.compile(
    r"raised|bonus|бонус|бюджет|budget|industry|market|valuation|\bARR\b|"
    r"revenue|funding|investment|інвестиц\w*|оборот|turnover|виторг|"
    r"courses?|certificat\w*|курс\w*",
    re.IGNORECASE,
)


def _tidy(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip(" .,;:")
    # Нерозривні пробіли всередині числа читаються гірше за звичайні.
    return text.replace(" ", " ")


def detect(description: str, salary: str = "") -> tuple[str, str]:
    """→ (бюджет як показувати, цитата-доказ). Порожньо — не знайшли.

    `salary` передається, щоб не дублювати те, що джерело вже дало полем:
    там воно надійніше за наш розбір тексту.
    """
    if salary:
        return "", ""
    text = re.sub(r"\s+", " ", description or "")
    if not text:
        return "", ""

    for match in MONEY.finditer(text):
        start = max(0, match.start() - WINDOW)
        end = min(len(text), match.end() + WINDOW)
        window = text[start:end]
        if STOP.search(window) or not CONTEXT.search(window):
            continue
        amount = _tidy(match.group("sum") + (match.group("period") or ""))
        # Голе число без валюти — не доказ: у вікні могло опинитись «2024»
        # поруч зі словом salary.
        if not re.search(rf"{_CURRENCY}|{_WORD_CURRENCY}", amount, re.IGNORECASE):
            continue
        return amount, _tidy(window)
    return "", ""
