"""Чи пускають нас джерела з чужої адреси — проба перед переїздом у хмару.

Питання, на яке відповідає: **чи віддадуть сайти дані, коли по них піде не
домашній комп'ютер, а машина GitHub.** Переїжджати, не спитавши, не можна:
якщо джерела відмовлять, переїзд не покращить сервіс, а зламає його.

Чому через `pipeline.collect()`, а не власний список адрес
----------------------------------------------------------
Бо власний список розійдеться з конфігом — і почне брехати саме тоді, коли
конфіг змінять. Проба ганяє ТІ САМІ адаптери з ТИМ САМИМ конфігом, тож
відповідає про справжній сервіс, а не про свою копію.

🔴 Чому дивимось на КІЛЬКІСТЬ, а не на «відповів»
-------------------------------------------------
Це вже пійманий у цьому проєкті клас: `uxjobsboard.com` і `designremotely.co`
віддають чесні HTTP 200 — і обидва мертві, нуль вакансій. «Сайт відповів» і
«сайт дав дані» — сусідні величини, і плутати їх ми вже навчені.

Тому кожне джерело порівнюється з ОПОРОЮ — скільки воно дало з домашньої
машини. Джерело, яке віддало менше половини опори, зламане так само, як те,
що віддало 403; просто мовчки.

⚠️ Чого ця проба НЕ доводить
-----------------------------
Що доступ стабільний. Блокування буває ймовірнісним: work.ua свого часу
пропускав **3 запити з 9** — той самий URL то 403, то 328 КБ даних. Один
зелений прогін такого не ловить у принципі.

Зелений результат означає рівно одне: **цього разу з цієї адреси пустили.**
Для рішення «чи переїжджати» цього досить лише разом із повторними пробами.

Стани й що кожен означає для результату
---------------------------------------
```
ok       дало вакансії                              зелений
empty    відповіло 200, але нуль вакансій           🔴 ЧЕРВОНИЙ
failed   виняток або не-200                         🔴 червоний
waiting  пропущене за власною періодичністю         не впливає
off      вимкнене в конфізі                         не впливає
```

`empty` червоний свідомо: саме так виглядали `uxjobsboard.com` і
`designremotely.co` — чесні 200 і жодної вакансії. «Відповіло» і «дало дані»
ми розрізняємо, і нуль тут не стан спокою.

⚠️ Ціна повного прогону — і вона більша за домашню
--------------------------------------------------
Проба не читає історію заборів (`previous_health=None`), тому добові джерела
забираються ЩОРАЗУ: `dou_companies` обходить усі 41 фід компаній,
`recruitee` — усіх своїх. Удома вони пропускаються 23 години з 24.

Тобто одна проба стукає в чужі сайти більше, ніж звичайний щогодинний
прогін. Для однієї перевірки це нормально; для «кількох проб у різні години»,
які потрібні, щоб побачити ймовірнісне блокування, — ні.

Тому є `--skip-daily`: добові джерела позначаються `waiting` і не
забираються. Повторні проби треба ганяти саме так, а повну — зрідка.

Запуск
------
    python tools/probe_cloud.py               # повна: усі джерела
    python tools/probe_cloud.py --skip-daily  # лише погодинні, для повторних
    gh workflow run probe-sources.yml         # вручну з вкладки Actions

Код виходу: 0 — усі ввімкнені джерела дали дані; 1 — хоч одне впало або
просіло. Власник дивиться на зелений/червоний у списку Actions, а не в лог.
"""

from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from jobfeed import config as config_module  # noqa: E402
from jobfeed import pipeline  # noqa: E402
from jobfeed.health import SourceHealth  # noqa: E402

# Скільки кожне джерело дало з ДОМАШНЬОЇ машини. Це опора для порівняння, а
# не очікування: числа живі й змінюються разом із ринком.
#
#   djinni/dou/boards_rss/jobico — замір координатора, прогін 21.10.2026 22:41
#   dou_companies/recruitee      — замір visual, 21.10.2026, цією ж пробою.
#                                  У координатора їх не було, і не випадково:
#                                  вдома вони пропускаються за добовою
#                                  періодичністю, а проба історії не читає —
#                                  тому забирає їх завжди.
BASELINE = {
    "djinni": 126,
    "dou": 25,
    "boards_rss": 100,
    "jobico": 336,
    "dou_companies": 254,
    "recruitee": 5,
}

# Нижче цієї частки від опори джерело вважається зламаним, навіть якщо
# відповіло без помилки. Половина — свідомо грубий поріг: він ловить
# «віддало дві вакансії замість ста», а не природні коливання ринку.
FLOOR = 0.5

# Опора, менша за цю, статистично беззмістовна: у recruitee одна вакансія,
# і «просіло вдвічі» там означає «стало нуль» — а нуль ми й так ловимо
# окремо, як порожнє джерело.
MIN_BASELINE = 5


def daily_as_waiting(config: dict) -> dict[str, SourceHealth]:
    """Підробна історія: «добові джерела щойно забирались».

    Не милиця, а той самий механізм, яким користується `run()`: він теж
    передає в `collect()` історію заборів, і саме з неї береться рішення
    «ще рано». Ми лише складаємо її самі, бо на раннері бази немає — вона
    свідомо не потрапила в репозиторій.

    Навіщо: без історії `dou_companies` обходить усі 41 фід КОЖНОГО разу.
    Для повторних проб, якими тільки й можна побачити ймовірнісне
    блокування, це зайвий стукіт у чужі двері.
    """
    now = datetime.now(timezone.utc).isoformat()
    history: dict[str, SourceHealth] = {}
    for source in pipeline.build_sources(config.get("sources", {})):
        if float(getattr(source, "every_hours", 0) or 0) > 0:
            history[source.name] = SourceHealth(name=source.name, last_try=now)
    return history


def verdict_for(health, baseline: int | None) -> tuple[str, bool]:
    """→ (пояснення, чи це провал). Провал = ввімкнене джерело не дало даних."""
    if health.state == "off":
        # 🔴 Вимкнене джерело — це НЕ нуль. Відсутність ми вже одного разу
        # прийняли за порожнечу, тому стан названий окремим словом.
        return f"вимкнене — {health.note[:60]}" if health.note else "вимкнене", False
    if health.state == "waiting":
        # Пропуск за власною періодичністю. Висновок на нього не спирається.
        return f"пропущене за періодичністю (ще {health.wait_hours} год)", False
    if health.state == "failed":
        return f"🔴 {health.error[:90]}", True
    if not health.fetched:
        return "🔴 відповіло, але не дало жодної вакансії", True
    if baseline and baseline >= MIN_BASELINE:
        share = health.fetched / baseline
        if share < FLOOR:
            return (f"🔴 просіло: {share:.0%} від опори — "
                    "мовчазна поломка, не відмова"), True
        note = f"{share:.0%} від опори"
        if not health.complete:
            # Обрізаний забір — успіх, що виглядає як повний успіх.
            note += " · забір НЕПОВНИЙ (уперлись у стелю сторінок)"
        return note, False
    return "опори для порівняння немає", False


def main() -> int:
    # Windows-консоль за замовчуванням cp1251 — кирилиця в ній падає.
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")

    skip_daily = "--skip-daily" in sys.argv
    started = datetime.now(timezone.utc)
    print(f"Проба джерел · {started:%Y-%m-%d %H:%M} UTC"
          + (" · полегшена (--skip-daily)" if skip_daily else " · повна"))
    print("Питання: чи віддадуть сайти дані з ЦІЄЇ адреси.\n")

    config = config_module.load("config/filter.toml")
    # 🔴 Без історії `_hours_until_due()` повертає 0 для ВСІХ, тобто добові
    # джерела забираються щоразу, а `waiting` не виникає ніколи. Це не
    # здогад: заміряно на справжніх обʼєктах конфіга, і `waiting` оживає
    # лише тоді, коли історію передати (контроль: `last_try=щойно` → 24.0).
    #
    # Повна проба саме цього й хоче — дізнатись, чи пускають і добові.
    # `--skip-daily` підставляє історію навмисно, щоб повторні проби не
    # ганяли 41 фід компаній заради питання про адресу.
    history = daily_as_waiting(config) if skip_daily else None
    vacancies, errors, _sources, healths = pipeline.collect(
        config, previous_health=history)

    print(f"{'джерело':<16}{'стан':<10}{'забрано':>8}{'опора':>8}   пояснення")
    print("─" * 100)
    failed: list[str] = []
    for name in sorted(healths):
        health = healths[name]
        baseline = BASELINE.get(name)
        note, bad = verdict_for(health, baseline)
        if bad:
            failed.append(name)
        print(f"{name:<16}{health.state:<10}"
              f"{health.fetched if health.state not in ('off', 'waiting') else '—':>8}"
              f"{baseline if baseline else '—':>8}   {note}")

    print("─" * 100)
    print(f"усього вакансій: {len(vacancies)}")
    if errors:
        print("\nпомилки забору:")
        for error in errors:
            print(f"  · {error}")

    print()
    if failed:
        print(f"🔴 ПРОВАЛ: {', '.join(failed)}")
        print("   З цієї адреси сервіс працював би гірше, ніж із домашньої машини.")
    else:
        print("🟢 Цього разу всі ввімкнені джерела дали дані з цієї адреси.")

    # ⚠️ Межа друкується ЗАВЖДИ, і разом із результатом, а не лише в
    # докстрінгу: читають вивід. Зелений рядок без цієї приписки
    # прочитається як «доступ стабільний», чого проба не доводить.
    print("\n⚠️  Чого ця проба НЕ доводить: що доступ стабільний. Блокування")
    print("    буває ймовірнісним — work.ua свого часу пропускав 3 запити з 9.")
    print("    Один прогін каже лише: цього разу з цієї адреси пустили.")
    print("    Для рішення про переїзд потрібні кілька проб у різні години.")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
